// Inu Empires sim id: sha256 over the five deterministic sim modules (the exact files kibble-pay vendors at
// public/lib/empires/ to replay matches for the One Inu Score). Any gameplay change = a new id, so a client running different
// rules can never be scored by a server replaying other rules (the server answers 409 "rules changed" instead).
// Usage: node scripts/sim-id.mjs            -> prints the id
//        node scripts/sim-id.mjs --write    -> writes src/sim-id.js
//        node scripts/sim-id.mjs --copy DIR -> copies the five files to DIR (kibble-pay public/lib/empires)
import { readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
export const SIM_FILES = ['sim.js', 'ai.js', 'combat.js', 'techtree.js', 'civs.js'];
export function simId(dir) { const h = createHash('sha256'); for (const f of SIM_FILES) { h.update(f + '\n'); h.update(readFileSync(new URL(f, dir))); } return h.digest('hex').slice(0, 16); }
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = new URL('../src/', import.meta.url), id = simId(src), a = process.argv;
  if (a.includes('--write')) writeFileSync(new URL('sim-id.js', src), `// generated by scripts/sim-id.mjs: sha256 of ${SIM_FILES.join(', ')} (kibble-pay replays matches with the same files)\nexport const SIM_ID = '${id}';\n`);
  const ci = a.indexOf('--copy'); if (ci > 0) for (const f of SIM_FILES) copyFileSync(new URL(f, src), a[ci + 1].replace(/\/?$/, '/') + f);
  console.log(id);
}
